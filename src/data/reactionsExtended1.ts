import type { SyllabusReactionSpec } from './reactionsCatalog';

type CompactRxn = {
  id: string;
  cat: SyllabusReactionSpec['category'];
  u: SyllabusReactionSpec['unitBadges'];
  siTitle: string;
  enTitle: string;
  siShort: string;
  enShort: string;
  a: string;
  b: string;
  cond?: SyllabusReactionSpec['defaultCondition'];
  eq: string;
  ion: string;
  dh: string;
  c0: string;
  c1: string;
  op0?: number;
  op1?: number;
  cb?: string;
  eff: SyllabusReactionSpec['effect'];
  ppt?: string;
  gas?: string;
  gasCol?: string;
  dt?: number;
  obsSi: string;
  obsEn: string;
  expSi: string;
  expEn: string;
  noteSi: string;
  noteEn: string;
};

export function expandCompactReaction(r: CompactRxn): SyllabusReactionSpec {
  return {
    id: r.id,
    category: r.cat,
    unitBadges: r.u,
    title: { si: r.siTitle, en: r.enTitle },
    shortTitle: { si: r.siShort, en: r.enShort },
    reagentAId: r.a,
    reagentBId: r.b,
    defaultCondition: r.cond ?? 'room',
    equation: r.eq,
    ionicEquation: r.ion,
    deltaHLabel: r.dh,
    initialColorHex: r.c0,
    finalColorHex: r.c1,
    initialOpacity: r.op0 ?? 0.65,
    finalOpacity: r.op1 ?? 0.9,
    reagentBColorHex: r.cb ?? '#e2e8f0',
    effect: r.eff,
    precipitateColorHex: r.ppt,
    gasColorHex: r.gasCol,
    gasName: r.gas,
    tempRiseC: r.dt ?? 2,
    observation: { si: r.obsSi, en: r.obsEn },
    explanation: { si: r.expSi, en: r.expEn },
    examNotes: { si: r.noteSi, en: r.noteEn },
    voiceSummary: { si: `${r.siTitle}. ${r.obsSi}`, en: `${r.enTitle}. ${r.obsEn}` },
  };
}

